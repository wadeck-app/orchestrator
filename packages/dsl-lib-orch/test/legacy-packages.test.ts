import fs from 'node:fs';
import path from 'node:path';

import { describe, expect, it } from 'vitest';
import { PACKAGE_DIR, PACKAGES_DIR } from '../src/paths.js';

/*
 * The React components and the DSL adapter used to be two packages (the UI package and the DSL library of
 * the orchestrator). They are one now. A mention of either old name is a stale import, script, CI step,
 * path or alias that would point at a folder that no longer exists, so any text mention fails this test.
 * Historical plans and specs under .claude/ describe the past and are not scanned.
 */
const FORBIDDEN = [['orch', 'ui'].join('-'), ['orch', 'dsl', 'lib'].join('-')];
const REPO = path.resolve(PACKAGES_DIR, '..');
const SKIPPED_DIRS = new Set(['node_modules', 'dist', 'dist-module', 'dist-bundle', '.git', '.cache', '.reports', '.app-core-dev']);
// Built or assembled copies, regenerated by the build and never edited.
const SKIPPED_PATHS = [path.join(PACKAGES_DIR, 'orch-server', 'public'), path.join(PACKAGES_DIR, 'orchestrator-cli', 'server'), path.join(PACKAGES_DIR, 'orchestrator-cli', 'app-module')];
const TEXT_FILE = /\.(ts|tsx|mts|cts|js|mjs|cjs|json|ya?ml|css|md|html|sh)$/;
const THIS_FILE = path.join(PACKAGE_DIR, 'test', 'legacy-packages.test.ts');

function listFiles(dir: string): string[] {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      return SKIPPED_DIRS.has(entry.name) || SKIPPED_PATHS.includes(full) ? [] : listFiles(full);
    }
    return TEXT_FILE.test(entry.name) && full !== THIS_FILE ? [full] : [];
  });
}

const files = [
  ...listFiles(PACKAGES_DIR),
  ...listFiles(path.join(REPO, '.github', 'workflows')),
  ...listFiles(path.join(REPO, 'scripts')),
  ...listFiles(path.join(REPO, '.violations')),
  ...['package.json', 'tsconfig.json', 'CLAUDE.md'].map((name) => path.join(REPO, name)),
];

describe('the former UI and DSL-library packages', () => {
  it('are scanned: an empty scan would pass for the wrong reason', () => {
    expect(files.length).toBeGreaterThan(100);
    expect(files.some((f) => f.endsWith('publish-orchestrator.yml'))).toBe(true);
  });

  it('are mentioned nowhere in packages/, the workflows, the scripts, the violations config or the root files', () => {
    const offenders = files.flatMap((file) => fs.readFileSync(file, 'utf8').split(/\r?\n/)
      .map((line, i) => (FORBIDDEN.some((word) => line.includes(word)) ? `${path.relative(REPO, file)}:${i + 1}: ${line.trim().slice(0, 120)}` : ''))
      .filter(Boolean));
    expect(offenders, 'the package is called @wadeck-app/dsl-lib-orch (packages/dsl-lib-orch): update these references').toEqual([]);
  });

  it('left no folder behind for either old package', () => {
    for (const word of FORBIDDEN) {
      expect(fs.existsSync(path.join(PACKAGES_DIR, word)), `packages/${word} must not exist`).toBe(false);
    }
  });
});
